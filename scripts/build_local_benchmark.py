"""Build a pose-reliability dataset from crystal structures, without Zenodo.

    # 1. fetch structures from RCSB (a few hundred KB each)
    python -m scripts.build_local_benchmark fetch --out data/local_set

    # 2. generate a pose ensemble per complex
    python -m scripts.build_local_benchmark poses --root data/local_set --n 20

    # 3. featurise with PoseBusters
    python -m scripts.build_bust_input data/local_set
    bust -t data/bust_input.csv --outfmt csv --full-report --output data/benchmark_raw.csv

WHAT IS REAL AND WHAT IS NOT
----------------------------
Real: the crystal structures, the crystal ligand geometry, the RMSD labels, and
every PoseBusters feature (bond lengths, angles, ring flatness, internal energy,
clash counts, protein distances).

Not docking: poses are generated by re-embedding the ligand and applying random
rigid-body rotations plus small translations about the crystallographic centroid,
rather than by a docking engine. This is the same construction the pose-filter
literature uses to define pose decoys (an ensemble of the cognate ligand labelled
by RMSD to the native pose), but it is not identical to a docking funnel and must
be described that way.
"""
