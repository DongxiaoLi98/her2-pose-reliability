# fetch
# --------------------------------------------------------------------------- #
def _get(url: str, timeout: int = 30) -> bytes:
    with urllib.request.urlopen(url, timeout=timeout) as r:
        return r.read()


def pick_ligand(pdb_text: str) -> tuple[str, str] | None:
    """Return (ccd_code, chain_resseq) of the largest non-trivial HETATM group."""
    groups: dict[tuple[str, str, str], int] = {}
    for line in pdb_text.splitlines():
        if not line.startswith("HETATM"):
            continue
        resn = line[17:20].strip()
        if resn in SKIP_HET or line[76:78].strip() == "H":
            continue
        key = (resn, line[21], line[22:27].strip())
        groups[key] = groups.get(key, 0) + 1
    if not groups:
        return None
    (resn, chain, resseq), n = max(groups.items(), key=lambda kv: kv[1])
    if n < 6:                      # too small to be a drug-like ligand
        return None
    return resn, f"{chain}|{resseq}"


def extract(pdb_text: str, ccd: str, loc: str) -> tuple[str, str]:
    """Split into (protein_pdb, ligand_pdb) keeping only the chosen ligand copy."""
    chain, resseq = loc.split("|")
    prot, lig = [], []
    for line in pdb_text.splitlines():
        rec = line[:6]
        if rec == "ATOM  ":
            prot.append(line)
        elif rec == "HETATM":
            if line[17:20].strip() == ccd and line[21] == chain and line[22:27].strip() == resseq:
                lig.append(line)
            # every other heteroatom (waters, ions, buffers) is dropped
    return "\n".join(prot) + "\nEND\n", "\n".join(lig) + "\nEND\n"


def ligand_mol(lig_pdb: str, ccd: str) -> Chem.Mol | None:
    """PDB records carry no bond orders; recover them from the CCD template."""
    raw = Chem.MolFromPDBBlock(lig_pdb, sanitize=False, removeHs=False)
    if raw is None:
        return None
    try:
        template = Chem.MolFromMolBlock(_get(RCSB_LIGAND.format(ccd=ccd)).decode(), sanitize=True)
        if template is not None:
            from rdkit.Chem import AllChem as _A

            return _A.AssignBondOrdersFromTemplate(template, raw)
    except Exception:
        pass
    try:
        Chem.SanitizeMol(raw)
        return raw
    except Exception:
        return None


def fetch(out: Path, ids: list[str], limit: int | None) -> None:
    out.mkdir(parents=True, exist_ok=True)
    ok, failed = 0, []
    for pdb in ids[: limit or len(ids)]:
        d = out / pdb
        if (d / f"{pdb}_ligand.sdf").exists():
            ok += 1
            continue
        try:
            text = _get(RCSB_ENTRY.format(pdb=pdb.upper())).decode("utf-8", "ignore")
            picked = pick_ligand(text)
            if picked is None:
                failed.append((pdb, "no drug-like ligand"))
                continue
            ccd, loc = picked
            prot, lig = extract(text, ccd, loc)
            mol = ligand_mol(lig, ccd)
            if mol is None or mol.GetNumHeavyAtoms() < 6:
                failed.append((pdb, "ligand did not parse"))
                continue
            d.mkdir(parents=True, exist_ok=True)
            (d / f"{pdb}_protein.pdb").write_text(prot)
            Chem.MolToMolFile(mol, str(d / f"{pdb}_ligand.sdf"))
            ok += 1
            print(f"  {pdb}  ligand={ccd}  heavy_atoms={mol.GetNumHeavyAtoms()}")
        except Exception as exc:
            failed.append((pdb, str(exc)[:60]))

    print(f"\nfetched {ok} complexes into {out}")
    if failed:
        print(f"skipped {len(failed)}:")
        for pdb, why in failed[:15]:
            print(f"  {pdb}: {why}")


# --------------------------------------------------------------------------- #
# pose ensemble
# --------------------------------------------------------------------------- #
def _axis_angle_rotation(rng, theta: float) -> np.ndarray:
    """Rotation of `theta` radians about a random axis.

    Sampling the ANGLE rather than a uniform random orientation is what lets us
    span the whole RMSD range. A uniformly random orientation is almost always
    far from native, which would put nearly every pose in the Fail class and
    leave the classifier nothing to learn near the decision boundary.
    """
    axis = rng.normal(size=3)
    axis /= np.linalg.norm(axis)
    x, y, z = axis
    c, s, t = np.cos(theta), np.sin(theta), 1 - np.cos(theta)
    return np.array([
        [t * x * x + c, t * x * y - s * z, t * x * z + s * y],
        [t * x * y + s * z, t * y * y + c, t * y * z - s * x],
        [t * x * z - s * y, t * y * z + s * x, t * z * z + c],
    ])


def perturb(mol: Chem.Mol, rng, max_shift: float, torsion: bool) -> Chem.Mol | None:
    """Rotate about the crystallographic centroid and shift slightly.

    Rotating about the centroid keeps the pose inside the pocket, so the decoys
    are geometrically wrong rather than trivially far away -- otherwise a
    distance-to-protein check alone would separate the classes and the task
    would be meaningless.

    The rotation angle and the shift are drawn together so the resulting RMSD
    spreads across the native-like, borderline and decoy ranges.
    """
    m = Chem.Mol(mol)
    if torsion:
        try:
            probe = Chem.AddHs(Chem.Mol(mol))
            if AllChem.EmbedMolecule(probe, randomSeed=int(rng.integers(1e6))) == 0:
                AllChem.MMFFOptimizeMolecule(probe, maxIters=200)
                probe = Chem.RemoveHs(probe)
                if probe.GetNumAtoms() == m.GetNumAtoms():
                    AllChem.AlignMol(probe, m)
                    m = probe
        except Exception:
            pass

    severity = rng.random()                       # 0 = almost native, 1 = decoy
    theta = severity * np.pi
    shift_scale = severity * max_shift

    conf = m.GetConformer()
    pos = np.array(conf.GetPositions())
    centroid = pos.mean(axis=0)
    new = (pos - centroid) @ _axis_angle_rotation(rng, theta).T + centroid
    if shift_scale > 0:
        new += rng.normal(scale=shift_scale / 2, size=3).clip(-shift_scale, shift_scale)
    for i, p in enumerate(new):
        conf.SetAtomPosition(i, p.tolist())
    return m


def make_poses(root: Path, n: int, seed: int, max_shift: float) -> None:
    rng = np.random.default_rng(seed)
    cases = [d for d in sorted(root.iterdir()) if d.is_dir()]
    total = 0
    for d in cases:
        crystal = d / f"{d.name}_ligand.sdf"
        if not crystal.exists():
            continue
        mol = Chem.MolFromMolFile(str(crystal))
        if mol is None:
            print(f"  {d.name}: crystal ligand did not parse, skipped")
            continue
        poses = d / "poses"
        poses.mkdir(exist_ok=True)
        # the crystal pose itself is the positive control the gate must not reject
        Chem.MolToMolFile(mol, str(poses / f"{d.name}_pose_000.sdf"))
        made = 1
        for k in range(1, n):
            p = perturb(mol, rng, max_shift, torsion=(k % 2 == 0))
            if p is None:
                continue
            Chem.MolToMolFile(p, str(poses / f"{d.name}_pose_{k:03d}.sdf"))
            made += 1
        total += made
    print(f"wrote {total} poses across {len(cases)} complexes under {root}")


def add_ids(table: Path) -> None:
    """The bust output identifies rows only by file path. Derive the group key.

    Without a group column there is nothing to split on, and the whole point of
    this dataset is that splitting happens at the complex level.
    """
    import pandas as pd

    df = pd.read_csv(table)
    if "file" not in df.columns:
        sys.exit("expected a 'file' column in the bust output")
    paths = df["file"].astype(str)
    df["pdb_id"] = paths.str.extract(r"([0-9A-Za-z]{4})[/\\]poses[/\\]")[0]
    df["pose_id"] = paths.str.rsplit("/", n=1).str[-1].str.replace(".sdf", "", regex=False)
    missing = df["pdb_id"].isna().sum()
    if missing:
        df["pdb_id"] = df["pdb_id"].fillna(paths.str.extract(r"([0-9A-Za-z]{4})")[0])
        print(f"  note: {missing} rows needed a fallback group key")
    df.to_csv(table, index=False)
    print(f"added pdb_id / pose_id to {table}: "
          f"{df['pdb_id'].nunique()} groups, {len(df)} rows")


# --------------------------------------------------------------------------- #
def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)

    f = sub.add_parser("fetch")
    f.add_argument("--out", default="data/local_set")
    f.add_argument("--limit", type=int, default=None)
    f.add_argument("--ids", nargs="*", default=None)

    p = sub.add_parser("poses")
    p.add_argument("--root", default="data/local_set")
    p.add_argument("--n", type=int, default=20)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--max-shift", type=float, default=3.0)

    i = sub.add_parser("ids")
    i.add_argument("--table", default="data/benchmark_raw.csv")

    a = ap.parse_args()
    if a.cmd == "fetch":
        fetch(Path(a.out), a.ids or DEFAULT_IDS, a.limit)
    elif a.cmd == "poses":
        root = Path(a.root)
        if not root.exists():
            sys.exit(f"{root} does not exist -- run the fetch step first")
        make_poses(root, a.n, a.seed, a.max_shift)
    else:
        add_ids(Path(a.table))


if __name__ == "__main__":
    main()
